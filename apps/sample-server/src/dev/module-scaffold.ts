import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Dev-only module scaffolder behind Menu Management's "Add with code" / "Delete with code".
 * It automates docs/add-module-checklist.md steps 1, 2, 5 and 6 (permissions file, registry
 * entry, App.tsx wiring, feature view). Every line it injects into a shared file ends with
 * `// @scaffold:<key>`, so removal deletes exactly those lines and nothing else.
 */

export interface ScaffoldInput {
  readonly key: string;
  readonly label: string;
  readonly path: string;
  readonly icon: string;
  readonly sortOrder: number;
}

export interface ScaffoldResult {
  readonly permissions: readonly { code: string; name: string; description: string }[];
  readonly moduleName: string;
}

const KEY_RE = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const ICON_RE = /^[a-z0-9-]+$/;

export function scaffoldRoot(): string {
  return join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
}

interface Targets {
  readonly serverIndex: string;
  readonly appTsx: string;
  readonly serverModuleDir: (key: string) => string;
  readonly webView: (key: string) => string;
}

export function scaffoldTargets(root: string): Targets {
  return {
    serverIndex: join(root, 'apps/sample-server/src/modules/index.ts'),
    appTsx: join(root, 'apps/sample-web/src/App.tsx'),
    serverModuleDir: (key) => join(root, 'apps/sample-server/src/modules', key),
    webView: (key) => join(root, 'apps/sample-web/src/features', `${key}.tsx`),
  };
}

const words = (key: string): string[] => key.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1));
const pascal = (key: string): string => words(key).join('');
/** Permission suffix, e.g. item-master -> Item_Master (matches `Read_Item_Master`). */
const permSuffix = (key: string): string => words(key).join('_');
const tag = (key: string): string => `// @scaffold:${key}`;

export const SCAFFOLD_ACTIONS = ['Read', 'Create', 'Update', 'Delete'] as const;

/** Permission codes a scaffolded module owns, e.g. item-master -> Read_Item_Master, ... */
export function scaffoldPermissionCodes(key: string): string[] {
  return SCAFFOLD_ACTIONS.map((a) => `${a}_${permSuffix(key)}`);
}

export function validateScaffoldInput(input: ScaffoldInput): string | null {
  if (!KEY_RE.test(input.key)) return 'Key must be lowercase letters, digits and single hyphens (e.g. item-master)';
  if (input.label.trim() === '') return 'Label is required';
  if (input.icon !== '' && !ICON_RE.test(input.icon)) return 'Icon must be a lowercase icon name (e.g. package)';
  if (input.label.includes("'") || input.label.includes('\\') || input.label.includes('`')) return 'Label cannot contain quotes or backslashes';
  return null;
}

function insertBeforeMarker(file: string, marker: string, line: string): void {
  const src = readFileSync(file, 'utf8');
  const lines = src.split('\n');
  const idx = lines.findIndex((l) => l.trim() === marker);
  if (idx === -1) throw new Error(`Scaffold marker "${marker}" not found in ${file}`);
  lines.splice(idx, 0, line);
  writeFileSync(file, lines.join('\n'));
}

function removeTaggedLines(file: string, key: string): void {
  if (!existsSync(file)) return;
  const suffix = tag(key);
  const kept = readFileSync(file, 'utf8').split('\n').filter((l) => !l.trimEnd().endsWith(suffix));
  writeFileSync(file, kept.join('\n'));
}

function hasTaggedLine(file: string, key: string): boolean {
  return existsSync(file) && readFileSync(file, 'utf8').split('\n').some((l) => l.trimEnd().endsWith(tag(key)));
}

/** Module keys whose code was generated by the scaffolder (and so can be removed by it). */
export function listScaffolded(root: string): string[] {
  const { serverIndex } = scaffoldTargets(root);
  if (!existsSync(serverIndex)) return [];
  const found = new Set<string>();
  for (const line of readFileSync(serverIndex, 'utf8').split('\n')) {
    const m = /\/\/ @scaffold:([a-z0-9-]+)$/.exec(line.trimEnd());
    // Bare marker lines (`// @scaffold:imports`) are anchors, not modules.
    if (m?.[1] && line.trim() !== m[0]) found.add(m[1]);
  }
  return [...found];
}

export function addModuleCode(root: string, input: ScaffoldInput): ScaffoldResult {
  const invalid = validateScaffoldInput(input);
  if (invalid !== null) throw new Error(invalid);
  const t = scaffoldTargets(root);
  const { key, label } = input;
  const P = pascal(key);
  const S = permSuffix(key);
  const moduleDir = t.serverModuleDir(key);
  if (existsSync(moduleDir) || existsSync(t.webView(key)) || hasTaggedLine(t.serverIndex, key)) {
    throw new Error(`Module "${key}" already has code in the repo; remove or rename it first`);
  }

  const permissions = [
    { code: `Read_${S}`, name: 'Read', description: `View ${label}` },
    { code: `Create_${S}`, name: 'Create', description: `Create ${label}` },
    { code: `Update_${S}`, name: 'Update', description: `Edit ${label}` },
    { code: `Delete_${S}`, name: 'Delete', description: `Delete ${label}` },
  ];

  mkdirSync(moduleDir, { recursive: true });
  writeFileSync(
    join(moduleDir, 'permissions.ts'),
    `import type { ModuleDefinition } from '@mawsoftwares/rbac-core';

// Generated by Menu Management (scaffold). Add API routes in main.ts when this module has an API.
export const ${key.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Module: ModuleDefinition = {
  key: '${key}',
  name: '${label}',
  routePrefix: '/api/v1/${key}',
  audience: 'admin',
  permissions: [
${permissions.map((p) => `    { code: '${p.code}', name: '${p.name} ${label}', description: '${p.description}' },`).join('\n')}
  ],
};
`,
  );

  mkdirSync(dirname(t.webView(key)), { recursive: true });
  writeFileSync(
    t.webView(key),
    `import type { ReactNode } from 'react';
import { ListPage, EmptyState, useDynamicAccess } from '@mawsoftwares/ui-web';

// Generated by Menu Management (scaffold). Replace the body with the real feature UI.
export function ${P}View(): ReactNode {
  const { can } = useDynamicAccess();
  const canCreate = can('Create_${S}');
  return (
    <ListPage title="${label}" createLabel="Create" onCreate={canCreate ? () => undefined : undefined}>
      <EmptyState title="${label}" message="This page was generated by Menu Management. Build the feature here." />
    </ListPage>
  );
}
`,
  );

  const moduleVar = `${key.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())}Module`;
  insertBeforeMarker(t.serverIndex, '// @scaffold:imports', `import { ${moduleVar} } from './${key}/permissions'; ${tag(key)}`);
  insertBeforeMarker(t.serverIndex, '// @scaffold:modules', `  ${moduleVar}, ${tag(key)}`);

  insertBeforeMarker(t.appTsx, '// @scaffold:imports', `import { ${P}View } from './features/${key}'; ${tag(key)}`);
  insertBeforeMarker(
    t.appTsx,
    '// @scaffold:nav',
    `  { key: '${key}', label: '${label}', icon: '${input.icon || 'circle'}', path: '${input.path || `/${key}`}', group: 'Main', sortOrder: ${Number(input.sortOrder) || 0}, permission: 'Read_${S}' }, ${tag(key)}`,
  );
  insertBeforeMarker(t.appTsx, '// @scaffold:permissions', `  '${key}': 'Read_${S}', ${tag(key)}`);
  insertBeforeMarker(t.appTsx, '// @scaffold:pages', `    case '${key}': return <${P}View />; ${tag(key)}`);
  insertBeforeMarker(t.appTsx, '// @scaffold:flags', `          'module.${key}': true, ${tag(key)}`);

  return { permissions, moduleName: label };
}

/** Removes everything addModuleCode generated. Returns false when the module was not scaffolded. */
export function removeModuleCode(root: string, key: string): boolean {
  if (!KEY_RE.test(key)) throw new Error('Invalid module key');
  const t = scaffoldTargets(root);
  if (!listScaffolded(root).includes(key)) return false;
  removeTaggedLines(t.serverIndex, key);
  removeTaggedLines(t.appTsx, key);
  rmSync(t.serverModuleDir(key), { recursive: true, force: true });
  rmSync(t.webView(key), { force: true });
  return true;
}
