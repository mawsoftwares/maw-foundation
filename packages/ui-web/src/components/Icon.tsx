export type IconName = keyof typeof PATHS;

const ALIASES: Record<string, IconName> = {
  dashboard: 'layout-dashboard',
  orders: 'shopping-cart',
  reports: 'bar-chart',
  inventory: 'clipboard-list',
  billing: 'credit-card',
  'audit-logs': 'scroll-text',
  account: 'lock',
  masters: 'database',
  rbac: 'key',
  'feature-flags': 'flag',
  platform: 'puzzle',
  jobs: 'clock',
  notifications: 'bell',
  showcase: 'palette',
  superadmin: 'shield',
};

function resolveIconName(name: string): IconName | undefined {
  if (name in PATHS) return name as IconName;
  return ALIASES[name];
}

export function isKnownIcon(name: string): boolean {
  return resolveIconName(name) !== undefined;
}

export interface IconProps {
  readonly name: string;
  readonly size?: number;
  readonly strokeWidth?: number;
  readonly style?: CSSProperties;
  readonly className?: string;
  readonly title?: string;
}

export function Icon({
  name,
  size = 18,
  strokeWidth = 1.75,
  style,
  className,
  title,
}: IconProps): ReactNode {
  const resolved = resolveIconName(name);
  if (resolved === undefined) {
    return (
      <span
        className={className}
        title={title}
        aria-hidden={title === undefined}
        style={{ fontSize: size, lineHeight: 1, display: 'inline-flex', ...style }}
      >
        {name}
      </span>
    );
  }

  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title === undefined}
      role={title === undefined ? undefined : 'img'}
      style={{ display: 'block', flexShrink: 0, ...style }}
    >
      {title !== undefined && <title>{title}</title>}
      {PATHS[resolved]}
    </svg>
  );
}
